_vs = lambda s: s.replace("\ufe0f", "")  # noqa: E731
_BY = {_vs(k): v for k, v in IDS.items()}
_RE = re.compile("(?<!\u200d)(?:" + "|".join(re.escape(k) for k in sorted(_BY, key=len, reverse=True)) + ")\ufe0f?(?!\u200d)")
_SPLIT = re.compile(r"(<[^>]*>)")
_OPEN = re.compile(r"^<(code|pre|tg-emoji)\b", re.I)
_CLOSE = re.compile(r"^</(code|pre|tg-emoji)>", re.I)


def premiumize(html: str) -> str:
    depth, out = 0, []
    for part in _SPLIT.split(html):
        if part.startswith("<") and part.endswith(">"):
            if _OPEN.match(part):
                depth += 1
            elif _CLOSE.match(part):
                depth = max(0, depth - 1)
            out.append(part)
        elif depth:
            out.append(part)
        else:
            out.append(_RE.sub(lambda m: f'<tg-emoji emoji-id="{_BY[_vs(m.group(0))]}">{m.group(0)}</tg-emoji>', part))
    return "".join(out)
