const picked = new Map<Daypart, number>()

/** Фраза для части суток: один раз за запуск — случайная, дальше та же. `rand` — для тестов. */
export function heroPhrase(part: Daypart, rand: () => number = Math.random): Phrase {
  const list = HERO_PHRASES[part]
  let i = picked.get(part)
  if (i === undefined) {
    i = Math.floor(rand() * list.length) % list.length
    picked.set(part, i)
  }
  return list[i]
}
